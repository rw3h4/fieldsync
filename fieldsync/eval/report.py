"""``uv run loadgen-report``: results/runs.csv -> results/summary.md (M4).

One table per test (every run plus the mean and min-max over runs), an overview
table, and the machine the runs were made on. Runs whose loadgen loop lag p95
exceeded 50 ms are marked harness-limited (D41): their limits belong to the
load generator, not to FieldSync.
"""

import argparse
import csv
import math
import os
import platform
import statistics
from collections.abc import Sequence
from pathlib import Path

from fieldsync.eval.loadgen import TESTS


# ========================================================== machine specs
def machine_specs() -> dict[str, str]:
    return {
        "CPU": _cpu_model(),
        "Logical CPUs": str(os.cpu_count()),
        "RAM": _ram(),
        "OS": platform.platform(),
        "Python": platform.python_version(),
        "Power": _power(),
    }


def _cpu_model() -> str:
    cpuinfo = Path("/proc/cpuinfo")
    if cpuinfo.exists():
        for line in cpuinfo.read_text(errors="replace").splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    return platform.processor() or "unknown"


def _ram() -> str:
    try:
        total = os.sysconf("SC_PAGE_SIZE") * os.sysconf("SC_PHYS_PAGES")
    except (AttributeError, ValueError, OSError):
        return "unknown"
    return f"{total / 2**30:.1f} GiB"


def _power() -> str:
    supplies = Path("/sys/class/power_supply")
    for ac in sorted(supplies.glob("A*")) if supplies.exists() else []:
        online = ac / "online"
        if online.exists():
            return "on AC power" if online.read_text().strip() == "1" else "on battery"
    return "unknown"


# ================================================================ tables
def _num(row: dict[str, str], key: str) -> float:
    value = row.get(key, "")
    return float(value) if value not in ("", "nan") else math.nan


def _f(x: float, digits: int = 1) -> str:
    return "-" if math.isnan(x) else f"{x:.{digits}f}"


def _agg(rows: Sequence[dict[str, str]], key: str, digits: int = 1) -> str:
    """Mean (min-max) over runs, ignoring missing values."""
    values = [v for v in (_num(r, key) for r in rows) if not math.isnan(v)]
    if not values:
        return "-"
    if len(values) == 1:
        return _f(values[0], digits)
    mean, lo, hi = (_f(x, digits) for x in (statistics.mean(values), min(values), max(values)))
    return f"{mean} ({lo}-{hi})"


def _table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


# (header, runs.csv column, digits)
MAIN_COLUMNS = [
    ("changes", "changes", 0),
    ("changes/s", "throughput_cps", 1),
    ("fwd msgs/s", "fwd_msgs_ps", 1),
    ("p50 ms", "lat_p50_ms", 1),
    ("p95 ms", "lat_p95_ms", 1),
    ("max ms", "lat_max_ms", 1),
    ("success %", "success_pct", 2),
    ("loop lag p95 ms", "loop_lag_p95_ms", 1),
]
FAULT_COLUMNS = [
    ("detection/failover s", "failover_s", 2),
    ("backlog cleared s", "recovery_s", 2),
    ("restored s", "restored_s", 2),
]
F2_COLUMNS = [
    ("online→online before p50/p95 ms", "f2_on_on_pre_p50_ms", "f2_on_on_pre_p95_ms"),
    ("online→online during outage p50/p95 ms", "f2_on_on_outage_p50_ms", "f2_on_on_outage_p95_ms"),
    ("offline-origin edits p50/p95 ms", "f2_offline_origin_p50_ms", "f2_offline_origin_p95_ms"),
]
PURPOSE = {
    "P1": "baseline latency",
    "P2": "moderate load",
    "P3": "scaling clients",
    "P4": "stress / throughput limit",
    "P4-mp": "P4 with the clients spread over 4 loadgen processes (D43)",
    "F1": "relay A killed 15 s into a P2 window: failover recovery",
    "F1b": "relay A hung (SIGSTOP) 15 s into a P2 window: heartbeat detection",
    "F2": "half the clients offline from 10 s to 40 s of a 50 s P2 window",
}


def _flags(row: dict[str, str]) -> str:
    flags = []
    if row["converged"] != "True":
        flags.append("NOT CONVERGED")
    if row["harness_limited"] == "True":
        flags.append("harness-limited")
    return ", ".join(flags) or "ok"


def render(rows: Sequence[dict[str, str]], specs: dict[str, str]) -> str:
    by_test: dict[str, list[dict[str, str]]] = {}
    for row in rows:
        by_test.setdefault(row["test"], []).append(row)
    order = [t for t in TESTS if t in by_test]

    lines = [
        "# M4 results summary",
        "",
        "Generated by `uv run loadgen-report` from `results/runs.csv`. Latencies are",
        "edit on the origin → apply on each other node (D41). Values over runs are",
        "**mean (min-max)**. A run is *harness-limited* when the load generator's own",
        "event-loop lag p95 exceeded 50 ms (D41); its limits are not attributed to FieldSync.",
        "",
        "## Machine",
        "",
        *_table(["", ""], list(specs.items())),
        "",
        "## Overview",
        "",
    ]
    overview = []
    for test in order:
        rs = by_test[test]
        spec = TESTS[test]
        overview.append(
            [
                test,
                str(spec.clients),
                f"{spec.clients * spec.rate:g}",
                _agg(rs, "throughput_cps"),
                _agg(rs, "lat_p50_ms"),
                _agg(rs, "lat_p95_ms"),
                _f(min(_num(r, "success_pct") for r in rs), 2),
                f"{sum(r['converged'] == 'True' for r in rs)}/{len(rs)}",
                str(sum(int(r["failovers"]) for r in rs)),
                f"{sum(r['harness_limited'] == 'True' for r in rs)}/{len(rs)}",
            ]
        )
    lines += _table(
        [
            "test",
            "clients",
            "offered changes/s",
            "changes/s",
            "p50 ms",
            "p95 ms",
            "min success %",
            "converged",
            "failovers",
            "harness-limited",
        ],
        overview,
    )

    for test in order:
        rs = sorted(by_test[test], key=lambda r: int(r["run"]))
        spec = TESTS[test]
        cols = MAIN_COLUMNS + (FAULT_COLUMNS if spec.fault else [])
        lines += [
            "",
            f"## {test}: {spec.clients} clients x {spec.rate:g} edits/s ({PURPOSE[test]})",
            "",
        ]
        body = [
            [r["run"], *(_f(_num(r, c), d) for _, c, d in cols), r["failovers"], _flags(r)]
            for r in rs
        ]
        body.append(["**all**", *(_agg(rs, c, d) for _, c, d in cols), "", ""])
        lines += _table(["run", *(h for h, _, _ in cols), "failovers", "status"], body)
        if test == "F2":
            lines += ["", "Latency split for F2 (D42):", ""]
            split = [
                [r["run"], *(f"{_f(_num(r, a))} / {_f(_num(r, b))}" for _, a, b in F2_COLUMNS)]
                for r in rs
            ]
            lines += _table(["run", *(h for h, _, _ in F2_COLUMNS)], split)
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="loadgen-report", description=__doc__)
    parser.add_argument("--results", type=Path, default=Path("results"))
    args = parser.parse_args(argv)
    with (args.results / "runs.csv").open(newline="") as f:
        rows = list(csv.DictReader(f))
    out = args.results / "summary.md"
    out.write_text(render(rows, machine_specs()), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
